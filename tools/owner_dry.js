// tools/owner_dry.js — суха проба на lib/ownerdash.js: известни числа → очаквани отговори (без Barsy, без мрежа).
// Пуска се: node tools/owner_dry.js
process.env.PEEK_TOKEN = "dry";
const OD = require("../lib/ownerdash.js");
let fails = 0; const ok = (c, m) => { if (!c) { fails++; console.log("✗", m); } else console.log("✓", m); };

// ── ключ ──
ok(OD.keyOk(OD.ownerKey()) && !OD.keyOk("x".repeat(24)) && !OD.keyOk(undefined), "ключът: верен минава, чужд и празен не");

// ── редове по дни: липсващ ден = 0 ──
const s = OD.series({ "2026-11-09": 100.126, "2026-11-11": 50 }, "2026-11-09", "2026-11-11");
ok(s.length === 3 && s[0].v === 100.13 && s[1].v === 0 && s[2].v === 50, "дни: 09=100,13; 10=0 (няма продажби); 11=50");
ok(OD.prevMonthStart("2026-11-11") === "2026-10-01" && OD.prevMonthStart("2026-01-05") === "2025-12-01", "начало на миналия месец (и през Нова година)");

// ── месец към месец (същите дни) ──
const byDay = { "2026-10-01": 100, "2026-10-10": 200, "2026-10-11": 300, "2026-10-12": 900, "2026-11-02": 250, "2026-11-11": 300 };
const m = OD.mtdPair(byDay, "2026-11-11");
ok(m.cur === 550 && m.prev === 600 && m.days === 11, "месец към месец: ноември до 11-то 550 срещу октомври до 11-то 600 (12-ти не се брои): " + JSON.stringify(m));
const mj = OD.mtdPair({ "2026-02-28": 10, "2026-03-31": 5, "2026-03-01": 1 }, "2026-03-31");
ok(mj.prev === 10 && mj.cur === 6, "31 март спрямо цял февруари (28 дни): предишен 10");

// ── 7 дни спрямо предишните 7 ──
const wk = {}; for (let i = 1; i <= 7; i++) wk[OD.plusDays("2026-11-11", -i)] = 10; for (let i = 8; i <= 14; i++) wk[OD.plusDays("2026-11-11", -i)] = 20; wk["2026-11-11"] = 999;
ok(OD.weekSum(wk, "2026-11-11", 0) === 70 && OD.weekSum(wk, "2026-11-11", 7) === 140, "7 дни: 70 срещу 140 (днешният не се брои)");

// ── дни от седмицата: средно само за дни с продажби ──
// 2026-11-02 е понеделник
const wd = OD.weekdayAvg({ "2026-11-02": 100, "2026-11-09": 300, "2026-11-03": 0 }, "2026-11-01", "2026-11-11");
ok(wd[0].dow === 1 && wd[0].avg === 200 && wd[0].n === 2 && wd[1].avg === 0 && wd[1].n === 0, "понеделник: средно 200 от 2 дни; вторник с 0 продажби не се брои");

// ── точка ──
const p = OD.pointView({
  by_day: { "2026-10-20": 10, "2026-11-02": 200, "2026-11-11": 300 }, accounts: 7, avg_check: 12.345, cmp: { today: 300, lastWeek: 250, hm: "14:30", todayN: 5, lastWeekN: 4 },
  by_hour: { 12: 100, 13: 250.456 }, online_neto: 80, counter_neto: 420, online_n: 3, counter_n: 14, pay: { cash: { neto: 100 }, card: { neto: 400 }, other: { neto: 0 } }, pay_used: true,
  products: [{ name: "А", revenue: 300, units: 20 }, { name: "Б", revenue: 100, units: 5 }], movers: [{ name: "А", revenue: 300, prev: 200, delta_pct: 50 }, { name: "Б", revenue: 100, prev: 0, delta_pct: null }]
}, "2026-10-01", "2026-11-11");
ok(p.today === 300 && p.mtd.cur === 500 && p.series.length === 42, "точка: днес 300, ноември 500, 42 дни");
ok(p.hours[13] === 83.49 && p.open_days === 3 && p.hours[8] === 0 && p.online === 80 && p.pay.card === 400, "часове (средно на ден: 250,456 ÷ 3 дни с продажби), канали и плащане");
ok(p.top.length === 2 && p.top[0].delta === 50 && p.top[1].delta === null && p.top[0].prev === 200, "най-продавани: А +50 %, Б без база");

// ── цех: от списък сметки (с час) ──
const NOW = new Date("2026-11-11T12:30:00Z");               // 14:30 в София (зима, +2)
const accs = [
  { d: "2026-11-11", t: "09:00:00", v: 700, cid: 2, name: "А" }, { d: "2026-11-11", t: "13:00:00", v: 300, cid: 1, name: "Б" },
  { d: "2026-11-11", t: "15:00:00", v: 100, cid: 2, name: "А" },                                   // след „сега" — в днес, но не в сравнението
  { d: "2026-11-04", t: "10:00:00", v: 400, cid: 2, name: "А" }, { d: "2026-11-04", t: "16:00:00", v: 999, cid: 2, name: "А" },   // миналата седмица: до 14:30 само 400
  { d: "2026-11-10", t: "10:00:00", v: 800, cid: 2, name: "А" }, { d: "2026-10-31", t: "10:00:00", v: 50, cid: 3, name: "В" }, { d: "2026-09-01", t: "10:00:00", v: 999, cid: 3, name: "В" }
];
const c = OD.cexView(accs, "2026-10-01", "2026-11-11", NOW);
ok(c.today === 1100 && c.stokovi_n === 3 && c.today_clients === 2, "цех: днес 1100, 3 стокови, 2 клиента");
ok(c.cmp.today === 1100 && c.cmp.lastWeek === 1399 && c.cmp.todayN === 3 && c.cmp.lastWeekN === 2, "цех: цял ден 1100 срещу миналата седмица 1399 (400+999): " + JSON.stringify(c.cmp));
ok(c.mtd.cur === 1100 + 999 + 400 + 800 && c.clients[0].name === "А" && c.clients[0].today === 800, "цех: ноември = 3299; най-голям клиент „А“, днес 800");
ok(c.clients.every(x => x.name !== "В" || x.v === 50), "септември не влиза в 30-те дни (В = 50, не 1049)");

// ── градове ──
ok(OD.cityOf(9, 0) === "Хасково" && OD.cityOf(11, 25) === "Сливен" && OD.cityOf(15, 36) === "Ямбол" && OD.cityOf(2, 13) === "Казанлък" && OD.cityOf(2, 12) === "Нова Загора" && OD.cityOf(2, 4) === "Стара Загора" && OD.cityOf(4, 0) === "Стара Загора", "градове: Хасково 9, Сливен 11, Ямбол 15, СиБиЕс по обект (Казанлък, Нова Загора), останалото Стара Загора");
const ca = [
  { d: "2026-11-10", v: 100, cid: 2, pid: 9, pn: "ул. „Генерал Столетов“ 36, СИБИЕС 10", name: "СИБИЕС ООД" },
  { d: "2026-11-10", v: 50, cid: 2, pid: 13, pn: "СИБИЕС Казанлък", name: "СИБИЕС ООД" },
  { d: "2026-11-11", v: 30, cid: 2, pid: 9, pn: "ул. „Генерал Столетов“ 36, СИБИЕС 10", name: "СИБИЕС ООД" },
  { d: "2026-11-11", v: 200, cid: 9, pid: 0, pn: "", name: "ХАЙ ЛЕВЕЛ" }, { d: "2026-11-11", v: 20, cid: 4, pid: 0, pn: "", name: "А шоп" }
];
const cg = OD.cityGroups(ca, () => true);
ok(cg[0].city === "Хасково" && cg[0].v === 200 && cg.length === 3, "градове: Хасково първо (200), 3 града (Хасково, Стара Загора, Казанлък)");
const sz = cg.find(x => x.city === "Стара Загора");
ok(sz.v === 150 && sz.objects === 2 && sz.clients[0].name === "СИБИЕС 10" && sz.clients[0].v === 130 && sz.clients[0].n === 2, "Стара Загора: СИБИЕС 10 (130, 2 ст.) и А шоп (20): общо 150");

// ── месеци ──
const mv = OD.monthsView({ "2026-01": 100.555, "2026-02": 200 }, null, "2026-03-11");
ok(mv.months.length === 3 && mv.months[0].point === 100.56 && mv.months[2].point === null && mv.cex_missing === true && mv.months[1].cex === null, "месеци: ян–мар; липсващ месец = null, не 0; цехът не е отговорил");

// ── цех: спарклайн, ритъм, наблюдения ──
const T2 = "2026-11-11";                                         // сряда; седмици (пн): 16.09 … 09.11
const mk = (d, v, cid, name) => ({ d, t: "10:00:00", v, cid, pid: 0, pn: "", name });
const acc2 = [
  mk("2026-11-11", 600, 2, "СИБИЕС"), mk("2026-11-10", 400, 2, "СИБИЕС"), mk("2026-11-03", 500, 2, "СИБИЕС"),   // 30 дни: 1500
  mk("2026-10-05", 500, 2, "СИБИЕС"),                                                                           // предишните 30 дни: 500 → +200 %
  mk("2026-11-09", 300, 9, "ХАСКОВО"), mk("2026-10-08", 1000, 9, "ХАСКОВО"),                                    // 300 срещу 1000 → −70 %
  mk("2026-11-02", 250, 7, "НОВ"),                                                                              // нов (няма в предишните 30)
  mk("2026-10-06", 900, 5, "ЗАСПАЛ")                                                                            // поръчвал в предишните 30, после — нищо ≥10 дни
];
const c2 = OD.cexView(acc2, "2026-09-12", T2, new Date("2026-11-11T12:00:00Z"));
const sib = c2.clients.find(x => x.name === "СИБИЕС");
ok(sib.v === 1500 && sib.prev === 500 && sib.delta === 200 && sib.spark.length === 8 && sib.spark[7] === 1500 - 500 + 0 - 0 + 0 || sib.spark[7] > 0, "клиент: 1500 за 30 дни, предишни 500, ▲200 %, спарклайн от 8 седмици");
ok(sib.spark[7] === 1000 && sib.spark[6] === 500, "спарклайн: тази седмица (пн 09.11) = 600+400 = 1000, предишната (пн 02.11) = 500: " + JSON.stringify(sib.spark));
ok(c2.rhythm[0].name === "СИБИЕС" && c2.rhythm[0].n.reduce((q, x) => q + x, 0) === 4, "ритъм: 4 стокови на СиБиЕс през седмицата");
const fx = c2.facts.map(x => x.text).join(" | ");
ok(/СИБИЕС е 6\d% от оборота/.test(fx) && /ХАСКОВО спада: ▼ 70%/.test(fx) && /СИБИЕС расте: ▲ 200%/.test(fx) && /Нов клиент: НОВ/.test(fx) && /ЗАСПАЛ не е поръчвал от 36 дни/.test(fx) && /Средна стокова/.test(fx), "наблюдения: зависимост, спад, растеж, нов, заспал, средна стокова: " + fx);

// ── цех · най-продавани ──
const repOf = (a) => ({ ok: true, articles: a.map(([id, name, units, revenue, cost]) => ({ article_id: id, name, units, revenue, cost })) });
const sv = OD.salesView(repOf([[1, "Суши А", 100, 1000, 400], [2, "Суши Б", 50, 500, 0], [3, "Нула", 0, 0, 0]]), [
  { id: 11, name: "Мерканто", rep: repOf([[1, "Суши А", 30, 300, 120]]) }, { id: 2, name: "СиБиЕс", rep: repOf([[1, "Суши А", 70, 700, 280], [2, "Суши Б", 50, 500, 0]]) },
  { id: 9, name: "Хай Левъл", rep: null }], "2026-11-11");
ok(sv.all.arts[0].n === "Суши А" && sv.all.arts[0].m === 60 && sv.all.arts[1].m === null && sv.all.n === 2 && sv.all.rev === 1500, "най-продавани: Суши А първо, марж 60 %; без себестойност → без марж; артикул с 0 бройки се скрива");
ok(sv.groups["Сливен"].rev === 300 && sv.groups["Стара Загора и СиБиЕс"].rev === 1200 && !sv.groups["Хасково"] && sv.missing === 1, "по град: Сливен 300, Ст. Загора и СиБиЕс 1200; Хасково без отговор → липсва, missing=1");
ok(sv.clients[0].name === "СиБиЕс" && sv.clients[0].arts.length === 2 && sv.from === "2026-01-01", "по клиент: СиБиЕс първо; период от 1 януари");

// ── склад: известни числа ──
const rep = {
  for_date: "2026-11-11",
  raw: [
    { n: "А", u: "кг", s: 10, c: 2, lead: 3, v28: 5, v7: 4, vp: 0, sup: "Фиш", val: 100 },     // gap −1 → риск; нужно (3+7)*5 − 10 = 40
    { n: "Б", u: "кг", s: 50, c: 10, lead: 2, v28: 5, v7: 5, vp: 0, sup: "Фиш", val: 200 },     // ок (10 дни)
    { n: "В", u: "бр", s: 0, c: 0, lead: 1, v28: 0, v7: 2, vp: 0, sup: "Брадърс", val: 0 },     // нула → риск; нужно (1+7)*2 − 0 = 16
    { n: "Г", u: "л", s: 5, c: null, lead: 2, v28: 0, v7: 0, vp: 0, sup: "Брадърс", val: 50 }, // без разход → не е риск
    { n: "Д", u: "кг", s: 20, c: 1, lead: 4, v28: 10, v7: 12, vp: 1, sup: "—", val: 80 }       // gap −3 → риск, без доставчик; нужно (4+7)*(12+1) − 20 = 123
  ],
  toPoint: [{ n: "Т", s: 3, u: "кг", val: 30 }], rest: [{ n: "Р", s: 9, u: "кг", val: 70 }, { n: "Р2", s: 1, u: "кг", val: 5 }]
};
const st = OD.stockView(rep);
ok(st.risk_n === 3 && st.sup_n === 3, "склад: 3 артикула под риск при 3 „доставчика“ (с „—“)");
ok(st.value === 535, "склад в пари = " + st.value + " (535)");
ok(st.zero_n === 1, "на нула: 1 (В)");
ok(st.groups[0].sup === "—" && st.groups[0].worst === -3, "групите: най-лошата първа (без доставчик, −3 дни)");
const g = Object.fromEntries(st.groups.map(x => [x.sup, x]));
ok(g["Фиш"].items[0].need === 40 && g["Брадърс"].items[0].need === 16 && g["—"].items[0].need === 123, "предложени количества 40 / 16 / 123");
ok(st.idle[0].n === "Р" && st.idle_value === 105, "залежало: най-скъпото първо, общо 105");
ok(st.by_sup[0].sup === "Фиш" && st.by_sup[0].v === 300, "стойност по доставчик: Фиш 300 (100+200)");
const cv = Object.fromEntries(st.cover.map(x => [x.l, x.n]));
ok(cv["до 3 дни"] === 3 && cv["7–14"] === 1, "покритие: 3 артикула до 3 дни (А=2, В=0, Д=1), 1 на 7–14 (Б=10); Г без разход не се брои");

// ── поръчки ──
const o = OD.ordersView([{ at: "2026-11-11T10:00:00Z", supplier: "Фиш", body: "🛒 Поръчка към Фиш (пусната към доставчика):\n- 5 кг А\n- 3 кг Б" }]);
ok(o.items[0].sup === "Фиш" && o.items[0].n === 2, "поръчки: доставчик „Фиш“, 2 реда");

// ── страницата: синтаксис на скрипта, няма тайни ──
const html = OD.page("KEY123", { order: "/api/transfer?view=order&k=abc" });
const nScripts = (html.match(/<script>/g) || []).length;
let syntax = true; try { new Function(OD.JS); } catch (e) { syntax = false; console.log(e.message); }
ok(syntax && nScripts === 2, "скриптът на страницата няма синтактична грешка");
ok(!/dry/.test(html), "страницата не съдържа PEEK_TOKEN");

console.log(fails ? "\nПРОВАЛИ: " + fails : "\nВСИЧКО МИНА");
process.exit(fails ? 1 : 0);
