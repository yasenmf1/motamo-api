/* Нов артикул в Барси още го няма в COSTS. Вместо да пада най-отдолу, приемаме
 * че прилича на другите в категорията си: медианният food cost като дял от
 * цената. Така се нарежда приблизително вярно от първия ден, а точното число
 * се добавя в COSTS, когато рецептата е ясна.
 */
const FALLBACK_FOOD_COST = {
  "Нигири/Сашими": 0.37,
  "ПОКЕ": 0.30,
  "Футомаки": 0.24,
  "Добавки": 0.24,
  "Комбо": 0.23,
  "Урамаки": 0.23,
  "Хосомаки": 0.22,
  "Салати": 0.21
};
const FALLBACK_DEFAULT = 0.28;

const VAT = 1.2;

/* Печалба от един артикул: цената без ДДС минус материали и опаковка.
 * Това е приносът, който остава за наем и заплати — не чиста печалба.
 */
function profitOf(item, category) {
  const net = Number(item.price) / VAT;
  if (!isFinite(net) || net <= 0) return -Infinity;
  const known = COSTS[item.id];
  const cost = typeof known === "number"
    ? known
    : net * (FALLBACK_FOOD_COST[category] || FALLBACK_DEFAULT);
  const pack = typeof PACKAGING[category] === "number" ? PACKAGING[category] : PACKAGING_DEFAULT;
  return net - cost - pack;
}

/* Подрежда артикулите в категорията — най-печелившото първо.
 *
 * Барси ги връща в реда, в който са заведени в касата, а той няма нищо общо с
 * това колко пари носят. При еднаква цена разликата стига 26 пункта: Токе
 * Криспи оставя 2.34 €, Хайко Норд 1.66 € — за същите 3.59 лв. Клиентът гледа
 * първите два-три реда, затова там стои това, което печели най-много.
 *
 * Сортира се копие, а не подаденият масив, и е стабилно при равни стойности.
 */
function sortByProfit(items, category) {
  return items
    .map(function (it, i) { return { it: it, i: i, p: profitOf(it, category) }; })
    .sort(function (a, b) { return (b.p - a.p) || (a.i - b.i); })
    .map(function (x) { return x.it; });
}

