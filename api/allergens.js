/**
 * Връща алергените на артикул: масив с имена, или `null` при неустановени и при
 * артикул, който изобщо не е в таблицата. Двете се показват еднакво на сайта —
 * и в двата случая честният отговор е „не знаем, питай", а не „няма".
 */
function allergensFor(articleId) {
  const id = PROMO_ALIAS[articleId] || articleId;
  const list = ALLERGENS[id];
  // `undefined` (няма ред) и `null` (има ред, но неустановени) стават едно и също.
  return Array.isArray(list) ? list.slice() : null;
}

